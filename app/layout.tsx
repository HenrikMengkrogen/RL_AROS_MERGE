import './globals.css'
import { Inter } from 'next/font/google'
import {Header} from "./structure"
import {DesignProvider} from './designContext';
import {ModeProvider} from './modeContext';
import {AdvancedProvider} from './advancedContext';
import { cookies } from "next/headers";

const inter = Inter({ subsets: ['latin'] })

export const metadata = {
  title: 'RL Designer',
  description: 'Generated by create next app',
}

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode
}) {
  const cookieStore = await cookies();
  const initialMode = cookieStore.get("mode")?.value === "true";
  return (
    <html lang="en">
      <body className={inter.className}>
        <DesignProvider>
        <div className='flex flex-row'>
          <ModeProvider  initialMode={initialMode ?? false}>
          <AdvancedProvider>
          <Header />
          <div className='flex flex-col h-screen items-center justify-center gap-y-8 py-16 px-16  w-3/4 border-4 border-double'>
          {children}
          </div>
          </AdvancedProvider>
          </ModeProvider>
        </div>
        </DesignProvider>
        
        </body>
    </html>
  )
}
